'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const app = 'app/src/main/java/com/ningshingche/app/';
test('book action is wired to a form and both dashboard entry routes', () => {
  const dashboard = read(app + 'ui/screens/UserDashboardScreen.kt');
  const host = read(app + 'ui/reader/ReaderNavHost.kt');
  assert.match(dashboard, /if \(pagerState.currentPage == TAB_HOME \|\| onContentTab\)/);
  assert.match(dashboard, /SpeedDialItem\(tNow\("বই যোগ"\)/);
  assert.equal((host.match(/onNewBook = \{/g) || []).length, 2);
  assert.match(host, /composable\(ReaderRoute.NewBook/);
  assert.match(dashboard, /myReaderBooks\(\)/);
});
test('PDF preflight is before uploads, verifies PDF bytes, then attempts requested fallback', () => {
  const ui = read(app + 'ui/screens/NewBookScreen.kt');
  const upload = read(app + 'data/remote/BookPdfUploader.kt');
  const satoru = read(app + 'data/remote/SatoruUploadClient.kt');
  assert.ok(ui.indexOf('bookSubmissionReady().getOrThrow()') < ui.indexOf('BookPdfUploader.upload(context, chosen)'));
  const policy = read(app + 'data/remote/BookPdfPolicy.kt');
  assert.match(policy, /25L \* 1024 \* 1024/);
  assert.match(policy, /%PDF-/);
  assert.match(upload, /isSmallerThanThreshold\(context, uri\)/);
  assert.match(upload, /tryImgBb\(context, uri\)/);
  assert.match(upload, /url.takeIf \{ it.isNotBlank\(\) && isHostedPdf\(it\) \}/);
  assert.match(upload, /SatoruUploadClient.uploadBookPdf\(context, uri\)/);
  assert.match(upload, /isHostedPdf\(uploaded.publicUrl\)/);
  const pdf = satoru.slice(satoru.indexOf('suspend fun uploadBookPdf'), satoru.indexOf('/** One multipart POST'));
  assert.doesNotMatch(pdf, /isTooLarge|MAX_BYTES/, 'no extra client cap');
  assert.match(satoru, /if \(declaredLength > 0L\) declaredLength else -1L/);
});
test('only a permitted reviewer publishes pending submissions atomically', () => {
  const sql = read('backend/supabase/migrations/052_reader_book_submissions.sql');
  assert.match(sql, /revoke all on public.reader_book_submissions from public, anon, authenticated/);
  assert.match(sql, /has_accepted_current_terms\(\)/);
  assert.match(sql, /moderation_restricted\(me,'publishing'\)/);
  assert.match(sql, /item.user_id=actor/);
  assert.match(sql, /where id=p_id for update/);
  assert.match(sql, /insert into public.pdf_books/);
  assert.match(sql, /item.status <> 'Pending'/);
  assert.match(sql, /grant execute on function public.submit_reader_book\([^;]+\) to authenticated/);
  const panel = read('backend/assets/js/books.js');
  assert.match(panel, /dashboard_book_submissions/);
  assert.match(panel, /dashboard_review_book/);
  assert.match(panel, /escapeHTML\(r.title\)/);
});
