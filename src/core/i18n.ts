export function getLang(): Lang {
  const v = localStorage.getItem(LANG_KEY) as Lang | null
  if (v === 'en' || v === 'bn') return v
  // default en; if previously 'both' treat as bn (bangla+english) fallback to bn
  const old = localStorage.getItem('mekholi:lang-pref') || localStorage.getItem('pref-lang')
  if (old === 'bn' || old === 'both') return 'bn'
  return 'en'
}

export function setLang(l: Lang) {
  localStorage.setItem(LANG_KEY, l)
  document.documentElement.lang = l
  window.dispatchEvent(new CustomEvent('mk:lang', { detail: l }))
  // also persist legacy key for old code
  localStorage.setItem('pref-lang', l)
}

export function t(key: keyof typeof dict.en | string, fallback?: string): string {
  const lang = getLang()
  const table: any = (dict as any)[lang] || (dict as any).en
  return table[key] ?? (dict.en as any)[key] ?? fallback ?? key
}

// helper to translate payment method ids
export function tPay(method: string): string {
  const map: Record<string,string> = {
    cash: t('pos.payCash'),
    bkash: t('pos.payBkash'),
    nagad: t('pos.payNagad'),
    rocket: t('pos.payRocket'),
    upay: t('pos.payUpay'),
    bangla_qr: t('pos.payBanglaQr'),
    card: t('pos.payCard'),
    due: t('pos.payDue'),
  }
  return map[method] ?? method
}

export function initI18n() {
  const l = getLang()
  document.documentElement.lang = l
}
